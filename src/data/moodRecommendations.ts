export function getRecommendationsForMood(mood?: MoodLevel | string | null): MoodRecommendationSet {
  if (!mood) return MOOD_RECOMMENDATIONS_DATA.happy;
  const key = mood.toLowerCase().trim() as MoodLevel;
  if (key in MOOD_RECOMMENDATIONS_DATA) {
    return MOOD_RECOMMENDATIONS_DATA[key];
  }
  return MOOD_RECOMMENDATIONS_DATA.happy;
}
